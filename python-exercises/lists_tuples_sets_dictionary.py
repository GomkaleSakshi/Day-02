"""Examples of Python's main built-in collection types."""

fruits = ["apple", "banana", "mango"]
fruits.append("orange")
print("List:", fruits)

coordinates = (12.5, 8.0)
print("Tuple:", coordinates)

unique_departments = {"Sales", "IT", "Sales", "HR"}
print("Set:", unique_departments)

student = {"name": "Asha", "age": 20, "course": "Python"}
student["age"] = 21
print("Dictionary:", student)